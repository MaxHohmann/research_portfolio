"""
This script generates the the condition table defining experimental variables for trials of the experiment.
Combinations are generated by first grouping files of each category with the same ID and then varrying the 
following parameters so that each file pairs contain opposite properties:
    - location on the screen    (left / right)
    - stimulus category         (face / house)
    - flicker frequency         (12Hz / 15Hz)
    - SWIFT frequency           (0.4Hz / 1Hz)

As result the condition tables contains 80 different combinations.


Version:    1.1
Date:       21/04/2026  
Author:     Maximilian Hohmann
            maximilian.hohmann@stud.uni-goettingen.de
"""

import os
import csv
import itertools


# ----- output path -----
COND_FOLDER = os.path.dirname(os.path.abspath(__file__))    # conditions/
out_path    = os.path.join(COND_FOLDER, 'condition_table.csv')


# ----- parameter -----
n_pairs         = 10                    # number of face-house pairs
screen_loc      = ['left', 'right']     # screen location
flicker_freq    = [12, 15]              # flicker frequencies in Hz
swift_freq      = [1, 1.2]              # SWIFT frequencies in Hz


# ----- generate table -----
with open(out_path, 'w', newline='') as f:
    writer = csv.DictWriter(f, fieldnames=[
        'ID',
        'left_file',
        'right_file',
        'left_category',
        'right_category',
        'left_flicker_Hz',
        'right_flicker_Hz',
        'left_swift_Hz',
        'right_swift_Hz'
    ])
    writer.writeheader()

    cond_ID = 0 # initialize condition ID

    for pair in range(1, n_pairs + 1):
        for side, flicker_pair, swift_pair in itertools.product(
            screen_loc,
            itertools.permutations(flicker_freq, 2),
            itertools.permutations(swift_freq, 2)
        ):
            # condition ID
            cond_ID += 1

            # flicker and SWIFT frequencies
            left_flicker, right_flicker = flicker_pair
            swift_face, swift_house     = swift_pair

            # category
            if side == 'left':
                left_category  = 'face'
                right_category = 'house'
                left_swift     = swift_face
                right_swift    = swift_house
            else:
                left_category  = 'house'
                right_category = 'face'
                left_swift     = swift_house
                right_swift    = swift_face

            # label
            left_swift_label = f"{int(left_swift * 1000)}mHz"
            right_swift_label = f"{int(right_swift * 1000)}mHz"

            # filename
            left_file  = f"{left_category}_{pair:02d}_swift_{left_swift_label}"
            right_file = f"{right_category}_{pair:02d}_swift_{right_swift_label}"

            # save
            writer.writerow({
                'ID':               cond_ID,
                'left_file':        left_file,
                'right_file':       right_file,
                'left_category':    left_category,
                'right_category':   right_category,
                'left_flicker_Hz':  left_flicker,
                'right_flicker_Hz': right_flicker,
                'left_swift_Hz':    left_swift,
                'right_swift_Hz':   right_swift
            })


print(f"generated {cond_ID} conditions")
print(f"saved table: {out_path}")

